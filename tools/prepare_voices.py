"""Render original dialogue with Piper and combine each voice into one Ogg bank.
Usage: python tools/prepare_voices.py /path/to/piper /path/to/model-directory [bank ...]
Current character banks: northern_english_male cori. Models use <bank>.onnx/json names.
Requires ffmpeg. Model cards and provenance are in actors/voices/.
"""
import json
import pathlib
import re
import subprocess
import sys
import tempfile
import wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
TEXT = (ROOT / 'actors/speech.gd').read_text()
LINES = dict(re.findall(r'"([a-z_]+)":"([^"\n]+)"', TEXT))
LINES.update(json.loads((ROOT/'actors/voices/dialogue-source.json').read_text()))

with tempfile.TemporaryDirectory() as task_dir:
    temp = pathlib.Path(task_dir)
    existing = (ROOT/'actors/voices/catalog.gd').read_text().split('const BANKS := ',1)[1]
    catalog = json.loads(existing)
    for voice in (sys.argv[3:] or ['alba', 'joe']):
        requests = [{'text': text, 'output_file': str(temp / (voice+'-'+key+'.wav'))}
                    for key, text in LINES.items()]
        subprocess.run([sys.argv[1], '--model', str(pathlib.Path(sys.argv[2]) / (voice+'.onnx')),
                        '--length_scale','0.92','--json-input'], input='\n'.join(json.dumps(r) for r in requests)+'\n',
                        text=True, check=True, timeout=360)
        combined = temp / (voice+'.wav')
        frames = bytearray()
        segments = {}
        rate = 22050
        for key in LINES:
            with wave.open(str(temp / (voice+'-'+key+'.wav'))) as wav:
                assert wav.getnchannels() == 1 and wav.getsampwidth() == 2
                rate = wav.getframerate()
                data = wav.readframes(wav.getnframes())
            start = len(frames)/2/rate
            segments[key] = {'start': start, 'duration': len(data)/2/rate, 'text': LINES[key]}
            frames.extend(data)
            frames.extend(bytes(rate//2*2))  # Half-second silent guard between phrases.
        with wave.open(str(combined), 'wb') as wav:
            wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(rate)
            wav.writeframes(frames)
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(combined), '-c:a', 'libvorbis',
                        '-q:a', '3', str(ROOT / 'actors/voices' / (voice+'.ogg'))], check=True)
        catalog[voice] = segments
        print(voice, 'generated', len(segments), 'spoken phrases', flush=True)
    (ROOT / 'actors/voices/catalog.gd').write_text('extends RefCounted\n# Generated by tools/prepare_voices.py.\nconst BANKS := '+json.dumps(catalog, indent=2)+'\n')
